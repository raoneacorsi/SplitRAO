export function createTranslator(getLang) {
  function t(chave, vars = {}) {
    const lang = getLang();
    const dict = I18N[lang] || I18N.pt;
    let str = dict[chave] !== undefined ? dict[chave] : (I18N.pt[chave] || chave);
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, v);
    }
    return str;
  }

  function getNomeCategoriaTraduzido(catId) {
    if (!catId || catId === 'Sem categoria') return t('catNoCategory');
    const mapKey = {
      Casa: 'catCasa',
      Comida: 'catComida',
      Carro: 'catCarro',
      Entretenimento: 'catEntretenimento',
      Transporte: 'catTransporte',
      Vida: 'catVida',
      "Mercado": 'catMercado',
      "Comer fora": 'catComerFora',
      "Saúde": 'catSaude',
      "Educação": 'catEducacao',
      "Presentes": 'catPresentes',
      "Lazer": 'catLazer',
      "Vestuário": 'catVestuario',
      "Seguros / Impostos": 'catSeguros',
      "Animais de estimação": 'catPets',
      "Geral": 'catGeral'
    };
    return mapKey[catId] ? t(mapKey[catId]) : catId;
  }

  return { t, getNomeCategoriaTraduzido };
}
